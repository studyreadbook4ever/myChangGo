def resolve_particles(text):
    """Resolve the author's Korean josa notation using the preceding syllable."""
    import re
    def replace(match):
        last, pair = match.groups()
        jong = (ord(last) - 0xAC00) % 28
        if pair in ('으로/로', '로/으로'):
            particle = '로' if jong in (0, 8) else '으로'
        else:
            particle = {'은/는': ('은', '는'), '이/가': ('이', '가'),
                        '을/를': ('을', '를'), '과/와': ('과', '와')}[pair][not bool(jong)]
        return last + particle
    return re.sub(r'([가-힣])(은/는|이/가|을/를|과/와|으로/로|로/으로)', replace, text)


def curriculum():
    data = [dict(w, exampleMeaning=resolve_particles(w['exampleMeaning'])) for w in WORDS]
    # Simple number characters precede compounds; authored order remains stable
    # for all other topics within the same estimated level.
    data.sort(key=lambda w: (-w['level'], 0 if w['topic'] == '숫자 읽기의 기초' else 1))
    chars = []
    for line in KANJI_ROWS.strip().splitlines():
        if not line.strip():
            continue
        character, korean, on, kun, hint = line.split('|')
        chars.append(dict(character=character, korean=korean,
                          onyomi=on.split(',') if on else [],
                          kunyomi=kun.split(',') if kun else [],
                          hint='기억 힌트(어원 설명 아님): ' + hint))
    assert len({w['id'] for w in data}) == len(data), 'Duplicate vocabulary ID'
    assert len({w['word'] for w in data}) == len(data), 'Duplicate spelling'
    assert len({k['character'] for k in chars}) == len(chars), 'Duplicate kanji'
    return data, chars


def wordbook(level, entries):
    def esc(value):
        return value.replace('|', '\\|').replace('\n', ' ')
    lines = [f'# N{level} 한자 단어장 — {len(entries)}개', '',
             '[학습 순서와 범위](../curriculum.md) · [전체 단어장](README.md)', '',
             '> N등급은 학습 순서를 위한 비공식 추정입니다. 공식 출제 목록이나 해당 급수의 전체 어휘가 아닙니다.', '',
             '읽기·뜻 열을 가리고 소리 내어 회상한 뒤 확인하세요. 외운 뒤에는 예문에서 다시 읽어 봅니다.', '']
    topics = list(dict.fromkeys(w['topic'] for w in entries))
    for topic in topics:
        lines += [f'## {topic}', '', '| 어휘 | 읽기 | 한국어 뜻 |', '|---|---|---|']
        group_entries = [w for w in entries if w['topic'] == topic]
        for word in group_entries:
            lines.append('| ' + ' | '.join(esc(word[key]) for key in ('word', 'reading', 'meaning')) + ' |')
        lines.append('')
        for w in group_entries:
            lines += [f'**{w["word"]}** · {w["example"]}',
                      f'- 읽기: {w["exampleReading"]}', f'- 뜻: {w["exampleMeaning"]}']
            if w['note']:
                lines.append(f'- 기억할 점: {w["note"]}')
            lines.append('')
    return '\n'.join(lines)


def render_outputs():
    words, chars = curriculum()
    outputs = {
        ROOT / 'assets/data/vocabulary.json': json.dumps(words, ensure_ascii=False, indent=2) + '\n',
        ROOT / 'assets/data/kanji.json': json.dumps(chars, ensure_ascii=False, indent=2) + '\n',
    }
    for level in range(5, 0, -1):
        entries = [w for w in words if w['level'] == level]
