    index = ['# 한자 단어장', '', '[커리큘럼과 공부 방법](../curriculum.md)', '',
             '앱과 동일한 원본에서 생성한 오프라인 단어장입니다. 한자·읽기·한국어 뜻·예문·주의점을 함께 제공합니다.', '',
             '| 학습 순서 | 단어 수 | 단어장 |', '|---|---:|---|']
