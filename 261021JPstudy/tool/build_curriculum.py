#!/usr/bin/env python3
"""Build the original Korean learner curriculum and its Markdown wordbooks.

Authored rows and context templates are the source of truth; no external dictionary
or copyrighted JLPT word list is downloaded. JLPT levels are editorial estimates.
"""
from __future__ import annotations
import hashlib
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WORDS: list[dict] = []


def group(level, topic, rows, sentence=None, note=''):
    for line in rows.strip().splitlines():
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        fields = line.split('|')
        word, reading, meaning = fields[:3]
        short = meaning.split(';')[0]
        if len(fields) >= 6:
            example, example_reading, example_meaning = fields[3:6]
            item_note = fields[6] if len(fields) > 6 else note
        else:
            assert sentence is not None, (word, fields)
            example, example_reading, example_meaning = [
                text.format(w=word, r=reading, m=short) for text in sentence
            ]
            item_note = fields[3] if len(fields) == 4 else note
        # IDs survive reordering, additions, and estimated-level changes.
        identifier = hashlib.sha256(f'{word}:{reading}'.encode()).hexdigest()[:12]
        WORDS.append(dict(id=f'jp_{identifier}', word=word, reading=reading,
                          meaning=meaning, level=level, topic=topic,
                          example=example, exampleReading=example_reading,
                          exampleMeaning=example_meaning, note=item_note))


