def main():
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if checked-in artifacts differ; do not write.')
    args = parser.parse_args()
    outputs, words, chars = render_outputs()
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8')
    if stale:
        raise SystemExit('Stale curriculum artifacts: ' + ', '.join(stale))
    counts = Counter(w['level'] for w in words)
    print(f'{"Checked" if args.check else "Built"} {len(words)} words, {len(chars)} kanji; '
          + ', '.join(f'N{level}={counts[level]}' for level in range(5, 0, -1)))


if __name__ == '__main__':
    main()
