export function localizedError(code: string, language: Language) {
  const key =
    code === "PROVIDER_TIMEOUT"
      ? "timeout"
      : /PROVIDER_NOT_CONFIGURED|MISSING_CREDENTIALS/.test(code)
        ? "provider"
        : /SESSION_/.test(code)
          ? "session"
          : /EMPTY_AUDIO|EMPTY_TRANSCRIPT|UNSUPPORTED_AUDIO|LIMIT_FILE_SIZE|NO_SPEECH|INVALID_AUDIO|AUDIO_TOO_LONG/.test(
                code,
              )
            ? "audio"
            : /STALE_CONFIRMATION|CONFIRMATION_EXPIRED|PRICE_CHANGED|MENU_CHANGED/.test(
                  code,
                )
              ? "review"
              : /BUSY|RATE_LIMITED|IN_PROGRESS|PROVIDER_HTTP_429/.test(code)
                ? "busy"
                : code === "OPERATOR_AUTH_REQUIRED"
                  ? "auth"
                  : /UNKNOWN_MENU|MENU_NOT_FOUND/.test(code)
                    ? "menu"
                    : "generic";
  return errorMessages[key][language];
}
